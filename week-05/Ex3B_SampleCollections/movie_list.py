# Working with lists
movie_list = ["Forrest Gump","The Batman", "Alien","Shrek","Scooby-Doo"]
print(f"The list [movie_list] inlcudes {len(movie_list)} of my favorite movies")
print(movie_list)

# Using sorted()
print(sorted(movie_list))
print(movie_list)
# The sorted() function lists the list in alphabetical order and without it it lists the list in the order the strings were put in

# Using .sort()
movie_list.sort()
print(movie_list)

